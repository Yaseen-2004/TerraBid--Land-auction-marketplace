import uuid
from datetime import datetime
from decimal import Decimal

from sqlalchemy import BigInteger, CheckConstraint, DateTime, Enum, ForeignKey, Index, Numeric, String, Uuid, func, text
from sqlalchemy.orm import Mapped, mapped_column

from app.database import Base
from app.models.enums import BidStatus


class Bid(Base):
    """Immutable bid ledger. A database trigger rejects UPDATE and DELETE on this table."""

    __tablename__ = "bids"
    __table_args__ = (
        CheckConstraint("amount > 0", name="amount_positive"),
        Index("ix_bids_auction_id_bid_time", "auction_id", text("bid_time DESC")),
        Index("ix_bids_bidder_id", "bidder_id"),
        Index(
            "ix_bids_accepted_amount",
            "auction_id",
            text("amount DESC"),
            postgresql_where=text("status = 'ACCEPTED'"),
        ),
    )

    # Generated by the API before the Redis script runs; doubles as the idempotent persistence key.
    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    auction_id: Mapped[int] = mapped_column(ForeignKey("auctions.id", ondelete="RESTRICT"), nullable=False)
    bidder_id: Mapped[int] = mapped_column(ForeignKey("users.id", ondelete="RESTRICT"), nullable=False)
    amount: Mapped[Decimal] = mapped_column(Numeric(14, 2), nullable=False)
    bid_time: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())
    status: Mapped[BidStatus] = mapped_column(Enum(BidStatus, name="bid_status"), nullable=False)
    rejection_reason: Mapped[str | None] = mapped_column(String(64))
    idempotency_key: Mapped[str | None] = mapped_column(String(128))
    # Redis state version at acceptance time (ordering of accepted bids).
    sequence: Mapped[int | None] = mapped_column(BigInteger)
