--[[
  Atomic bid placement.

  Redis executes a script as a single, uninterruptible operation, so the
  read -> validate -> compare -> write sequence below can never interleave
  with another bid. Two simultaneous bids are therefore evaluated one after
  the other against the latest state, and at most one of them can become
  the highest bid for any given price level.

  KEYS[1]  auction state hash         auction:{<id>}
  KEYS[2]  idempotency result hash    auction:{<id>}:idem
  KEYS[3]  persistence stream         bids:stream

  ARGV[1]  auction id
  ARGV[2]  bidder id
  ARGV[3]  bidder display name
  ARGV[4]  bid amount in minor units (paise), integer
  ARGV[5]  bid id (UUID generated by the API)
  ARGV[6]  idempotency key ('' when absent)
  ARGV[7]  current price the client saw, minor units ('' when absent; only used to pick an error message)

  Money values are returned as strings so large amounts never lose precision in cjson.
]]

local state_key = KEYS[1]
local idem_hash = KEYS[2]
local stream_key = KEYS[3]

local auction_id = ARGV[1]
local bidder_id = ARGV[2]
local bidder_name = ARGV[3]
local amount = tonumber(ARGV[4])
local bid_id = ARGV[5]
local idem = ARGV[6]
local expected = tonumber(ARGV[7])

local function fmt(n)
  return string.format('%d', n)
end

if redis.call('EXISTS', state_key) == 0 then
  return cjson.encode({code = 'NOT_LOADED', accepted = false})
end

local idem_field = false
if idem ~= '' then
  idem_field = bidder_id .. ':' .. idem
  local previous = redis.call('HGET', idem_hash, idem_field)
  if previous then
    local decoded = cjson.decode(previous)
    decoded.duplicate = true
    return cjson.encode(decoded)
  end
end

-- Redis' own clock is the single time authority for expiry checks.
local t = redis.call('TIME')
local now_ms = tonumber(t[1]) * 1000 + math.floor(tonumber(t[2]) / 1000)

local s = redis.call('HMGET', state_key,
  'auction_status', 'start_ms', 'end_ms', 'starting_price', 'min_increment',
  'highest_bid', 'highest_bidder', 'highest_bidder_name', 'bid_count',
  'version', 'epoch', 'seller_id')

local status = s[1] or ''
local start_ms = tonumber(s[2]) or 0
local end_ms = tonumber(s[3]) or 0
local starting_price = tonumber(s[4]) or 0
local min_increment = tonumber(s[5]) or 0
local highest_bid = tonumber(s[6]) or 0
local highest_bidder = s[7] or ''
local highest_bidder_name = s[8] or ''
local bid_count = tonumber(s[9]) or 0
local version = tonumber(s[10]) or 0
local epoch = s[11] or '0'
local seller_id = s[12] or ''

local function snapshot(code, accepted)
  local current = starting_price
  local min_next = starting_price
  if bid_count > 0 then
    current = highest_bid
    min_next = highest_bid + min_increment
  end
  return {
    code = code,
    accepted = accepted,
    duplicate = false,
    auction_id = auction_id,
    bid_id = bid_id,
    bidder_id = bidder_id,
    amount = fmt(amount or 0),
    auction_status = status,
    current_price = fmt(current),
    min_next_bid = fmt(min_next),
    highest_bidder_id = highest_bidder,
    highest_bidder_name = highest_bidder_name,
    bid_count = bid_count,
    version = version,
    epoch = epoch,
    server_time_ms = fmt(now_ms),
    end_ms = fmt(end_ms)
  }
end

local function finish(code, accepted, extra)
  local result = snapshot(code, accepted)
  if extra then
    for k, v in pairs(extra) do result[k] = v end
  end
  local encoded = cjson.encode(result)
  if idem_field then
    redis.call('HSET', idem_hash, idem_field, encoded)
  end
  return encoded
end

if amount == nil or amount <= 0 or amount ~= math.floor(amount) then
  return finish('INVALID_AMOUNT', false)
end
if status == 'CANCELLED' then
  return finish('AUCTION_CANCELLED', false)
end
if status == 'ENDED' or now_ms >= end_ms then
  return finish('AUCTION_ENDED', false)
end
if status ~= 'LIVE' or now_ms < start_ms then
  return finish('AUCTION_NOT_LIVE', false)
end
if seller_id ~= '' and seller_id == bidder_id then
  return finish('UNAUTHORIZED_BIDDER', false)
end
if bid_count > 0 and highest_bidder == bidder_id then
  return finish('ALREADY_HIGHEST_BIDDER', false)
end

local required = starting_price
if bid_count > 0 then
  required = highest_bid + min_increment
end

if amount < required then
  if expected ~= nil and bid_count > 0 and highest_bid > expected then
    return finish('OUTBID', false)
  end
  return finish('BID_TOO_LOW', false)
end

-- Accept: update state and enqueue for durable persistence in the same atomic step.
version = version + 1
bid_count = bid_count + 1
highest_bid = amount
highest_bidder = bidder_id
highest_bidder_name = bidder_name

redis.call('HSET', state_key,
  'highest_bid', fmt(amount),
  'highest_bidder', bidder_id,
  'highest_bidder_name', bidder_name,
  'last_bid_time', fmt(now_ms),
  'bid_count', fmt(bid_count),
  'version', fmt(version))

local stream_id = redis.call('XADD', stream_key, '*',
  'bid_id', bid_id,
  'auction_id', auction_id,
  'bidder_id', bidder_id,
  'amount', fmt(amount),
  'bid_time_ms', fmt(now_ms),
  'version', fmt(version),
  'idem', idem)

return finish('ACCEPTED', true, {stream_id = stream_id})
